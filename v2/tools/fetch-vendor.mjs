// Vendors every remote asset Memory Prism needs so the app runs offline.
// Usage: node tools/fetch-vendor.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const vendor = path.join(root, 'vendor');
const fontsDir = path.join(root, 'fonts');
for (const d of [vendor, fontsDir]) fs.mkdirSync(d, { recursive: true });

const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

async function get(url, as = 'text') {
  const res = await fetch(url, { headers: { 'user-agent': UA } });
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return as === 'buffer' ? Buffer.from(await res.arrayBuffer()) : await res.text();
}

const FILES = [
  ['https://cdn.quilljs.com/1.3.6/quill.js', 'vendor/quill.js'],
  ['https://cdn.quilljs.com/1.3.6/quill.snow.css', 'vendor/quill.snow.css'],
  ['https://cdn.jsdelivr.net/npm/dompurify@3.3.0/dist/purify.min.js', 'vendor/purify.min.js'],
];

for (const [url, dest] of FILES) {
  const buf = await get(url, 'buffer');
  fs.writeFileSync(path.join(root, dest), buf);
  console.log(`saved ${dest} (${buf.length} bytes)`);
}

// --- Google Fonts: keep only the latin subsets we actually ship ---------------
const cssUrl = 'https://fonts.googleapis.com/css2?family=Roboto:wght@400;500;700&family=Alegreya:wght@400;500;700&display=swap';
const css = await get(cssUrl);
const blocks = css.split(/\/\*\s*([a-z0-9-]+)\s*\*\//i);
const faces = [];
const seen = new Map(); // url -> local path (Google serves one variable file per family)
for (let i = 1; i < blocks.length; i += 2) {
  const subset = blocks[i].trim();
  const body = blocks[i + 1] || '';
  if (subset !== 'latin') continue;
  const family = /font-family:\s*'([^']+)'/.exec(body)?.[1];
  const weight = /font-weight:\s*(\d+)/.exec(body)?.[1];
  const url = /url\((https:[^)]+)\)/.exec(body)?.[1];
  const range = /unicode-range:\s*([^;]+);/.exec(body)?.[1];
  if (!family || !weight || !url) continue;
  let rel = seen.get(url);
  if (!rel) {
    const slug = family.toLowerCase().replace(/[^a-z0-9]+/g, '-');
    rel = `fonts/${slug}.woff2`;
    const buf = await get(url, 'buffer');
    fs.writeFileSync(path.join(root, rel), buf);
    seen.set(url, rel);
    console.log(`saved ${rel} (${buf.length} bytes)`);
  }
  faces.push({ family, weight, rel, range });
}

const fontCss = `/* Generated by tools/fetch-vendor.mjs - latin subsets only. */
${faces.map(f => `@font-face {
  font-family: '${f.family}';
  font-style: normal;
  font-weight: ${f.weight};
  font-display: swap;
  src: url('../${f.rel}') format('woff2');
  unicode-range: ${f.range};
}`).join('\n\n')}
`;
fs.writeFileSync(path.join(root, 'styles/fonts.css'), fontCss);
console.log('saved styles/fonts.css');

// --- Icons: inline SVG symbols, no runtime icon library ----------------------
const ICONS = [
  'check', 'save', 'folder-open', 'plus', 'download', 'scan-search', 'x',
  'pencil-line', 'calendar-days', 'undo-2', 'file-down', 'triangle-alert',
  'image', 'volume-2', 'video', 'search', 'arrow-left', 'external-link', 'clock-3',
  'sun', 'moon', 'trash-2',
];
const symbols = [];
for (const name of ICONS) {
  let svg;
  try {
    svg = await get(`https://cdn.jsdelivr.net/npm/lucide-static@0.468.0/icons/${name}.svg`);
  } catch (err) {
    console.warn(`skip icon ${name}: ${err.message}`);
    continue;
  }
  const inner = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>[\s\S]*$/, '')
    .replace(/\s+/g, ' ')
    .trim();
  symbols.push(`  <symbol id="i-${name}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${inner}</symbol>`);
  console.log(`icon ${name}: ${inner.length} chars`);
}
fs.writeFileSync(
  path.join(root, 'vendor/icons.svg.html'),
  `<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true" style="display:none" id="icon-sprite">\n${symbols.join('\n')}\n</svg>\n`
);
console.log('saved vendor/icons.svg.html');
